"""Summarize complete Ahrens recording-length fits.

Input is ``test.txt`` in each hash-named fit directory generated by
``ahrens_length_lowpass_four``. Required columns are ``TestLoss`` and
``<dataset_label>_test_score``. Output is one unique directory under the
configured ``figures`` artifact root containing five PDFs (four
subjects and their equal-weight mean) and ``summary.csv`` with model,
nominal length, population, test-score mean/standard error, test-loss
mean/standard error, and population count. No fit artifacts are copied.
"""

from datetime import datetime, timezone
from pathlib import Path
from textwrap import fill

import numpy as np
import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

from analysis import plots
from configs.campaigns.ahrens_length import load_ahrens_length_campaign
from configs.config_global import FIG_DIR
from configs.experiments import ahrens_length_lowpass_four
from utils.artifacts import fit_id, validate_complete

FIGURE_WIDTH = 7.2
FIGURE_HEIGHT = 6.0
LINE_WIDTH = 2.0
TITLE_WIDTH = 55
X_MARGIN = 0.08
Y_MARGIN = 0.08
METRICS = (
    ('test_score', 'Test score relative to last-frame copy'),
    ('test_loss', 'Test loss (MSE)'),
)


def read_fit_results() -> pd.DataFrame:
    """Read one finite test result for each required completed fit.

    Returns
    -------
    pandas.DataFrame
        Rows keyed by subject, model, length, and seed.
    """
    settings = load_ahrens_length_campaign()
    records = []
    for seed, configs in ahrens_length_lowpass_four().items():
        for config in configs:
            if not validate_complete(config):
                raise ValueError(
                    f'Incomplete fit {fit_id(config)}: {config.save_path}'
                )
            label = config.dataset_label[0]
            path = Path(config.save_path) / 'test.txt'
            table = pd.read_table(path)
            score_column = f'{label}_test_score'
            if len(table) != 1 or score_column not in table:
                raise ValueError(
                    f'Expected one test row with {score_column} in {path}.'
                )
            score = float(table[score_column].iloc[0])
            loss = float(table['TestLoss'].iloc[0])
            if not np.isfinite((score, loss)).all():
                raise ValueError(f'Non-finite test metrics in {path}.')
            records.append({
                'subject': label.partition('-')[2],
                'model': config.model_label,
                'nominal_length': config.train_data_length,
                'seed': seed,
                'test_score': score,
                'test_loss': loss,
            })
    expected = (
        len(settings['subjects']) * len(settings['models']) *
        len(settings['nominal_lengths']) * settings['seeds']
    )
    if len(records) != expected:
        raise ValueError(
            f'Expected {expected} completed fits, got {len(records)}.'
        )
    return pd.DataFrame.from_records(records)


def subject_means(results: pd.DataFrame) -> pd.DataFrame:
    """Average seeds within each subject and scientific condition.

    Parameters
    ----------
    results : pandas.DataFrame
        Complete per-fit metrics.

    Returns
    -------
    pandas.DataFrame
        Subject means across seeds for each model and length.
    """
    keys = ['subject', 'model', 'nominal_length']
    return results.groupby(keys, as_index=False)[
        ['test_score', 'test_loss']
    ].mean()


def summarize_population(
    results: pd.DataFrame, population: str,
) -> pd.DataFrame:
    """Compute mean and standard error across rows in one population.

    Parameters
    ----------
    results : pandas.DataFrame
        Repeated seed results or subject means.
    population : str
        Subject name or ``four_subject_mean``.

    Returns
    -------
    pandas.DataFrame
        One summary row per model and nominal length.
    """
    keys = ['model', 'nominal_length']
    summary = results.groupby(keys).agg(
        test_score_mean=('test_score', 'mean'),
        test_score_std=('test_score', 'std'),
        test_loss_mean=('test_loss', 'mean'),
        test_loss_std=('test_loss', 'std'),
        count=('test_score', 'size'),
    ).reset_index()
    if (summary['count'] < 2).any():
        raise ValueError(
            f'Population {population} needs at least two repeats.'
        )
    for metric in ('test_score', 'test_loss'):
        summary[f'{metric}_sem'] = (
            summary[f'{metric}_std'] / np.sqrt(summary['count'])
        )
        summary = summary.drop(columns=f'{metric}_std')
    summary.insert(0, 'population', population)
    if not np.isfinite(summary.select_dtypes(include='number')).all().all():
        raise ValueError(f'Non-finite summary for {population}.')
    return summary


def plot_population(summary: pd.DataFrame, path: Path) -> None:
    """Save a paired score/loss PDF using shared model colors.

    Parameters
    ----------
    summary : pandas.DataFrame
        One population with mean and standard error columns.
    path : Path
        New PDF output path.
    """
    sns.set_theme(style='ticks', context='paper')
    models = ['POCO', 'NLinear']
    colors = dict(zip(models, plots.get_model_colors(models)))
    fig, axes = plt.subplots(2, 1, figsize=(FIGURE_WIDTH, FIGURE_HEIGHT))
    for ax, (metric, ylabel) in zip(axes, METRICS):
        for model in models:
            rows = summary.loc[summary['model'] == model].sort_values(
                'nominal_length'
            )
            if rows.empty:
                raise ValueError(f'Missing {model} results in {path}.')
            x = rows['nominal_length'].to_numpy(dtype=float)
            mean = rows[f'{metric}_mean'].to_numpy(dtype=float)
            sem = rows[f'{metric}_sem'].to_numpy(dtype=float)
            sns.lineplot(
                x=x, y=mean, ax=ax, color=colors[model],
                linewidth=LINE_WIDTH, marker='o', label=model,
                linestyle='-' if model == 'POCO' else '--',
            )
            ax.fill_between(
                x, mean - sem, mean + sem,
                color=colors[model], alpha=0.18,
            )
        limits = summary[
            [f'{metric}_mean', f'{metric}_sem']
        ].to_numpy(dtype=float)
        lower = np.min(limits[:, 0] - limits[:, 1])
        upper = np.max(limits[:, 0] + limits[:, 1])
        span = upper - lower
        if span <= 0:
            raise ValueError(f'No {metric} range for {path}.')
        ax.set_ylim(lower - Y_MARGIN * span, upper + Y_MARGIN * span)
        ax.set_xscale('log', base=2)
        lengths = np.sort(summary['nominal_length'].unique())
        ax.set_xlim(lengths[0] * (1 - X_MARGIN),
                    lengths[-1] * (1 + X_MARGIN))
        ax.set_xticks(lengths, labels=[str(x) for x in lengths])
        ax.set_ylabel(ylabel)
        ax.legend().remove()
        sns.despine(ax=ax)
    axes[-1].set_xlabel('Nominal recording length (frames; 60% train cap)')
    axes[0].set_xlabel('')
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(
        handles, labels, loc='lower center', bbox_to_anchor=(0.5, 0.01),
        ncol=len(models), frameon=False,
    )
    title = summary['population'].iloc[0].replace('_', ' ')
    fig.suptitle(fill(f'Low-pass Ahrens: {title}', TITLE_WIDTH), y=0.98)
    fig.tight_layout(rect=(0, 0.07, 1, 0.94))
    fig.savefig(path)
    plt.close(fig)


def analyze_ahrens_length() -> Path:
    """Save subject and equal-weight mean summaries to a new folder.

    Returns
    -------
    Path
        Absolute artifact folder containing figures and summary.csv.
    """
    results = read_fit_results()
    settings = load_ahrens_length_campaign()
    means = subject_means(results)
    summaries = []
    for subject in settings['subjects']:
        subset = results.loc[results['subject'] == subject]
        summaries.append(summarize_population(subset, subject))
    summaries.append(summarize_population(means, 'four_subject_mean'))
    stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S.%fZ')
    root = Path(FIG_DIR) / 'ahrens_length_lowpass_four' / stamp
    root.mkdir(parents=True)
    combined = pd.concat(summaries, ignore_index=True)
    combined.to_csv(root / 'summary.csv', index=False)
    for summary in summaries:
        population = summary['population'].iloc[0]
        plot_population(summary, root / f'{population}.pdf')
    print(f'Saved Ahrens length figures: {root.resolve()}')
    return root
